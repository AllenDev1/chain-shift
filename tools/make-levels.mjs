// Builds js/levels.js: the campaign, generated from seeds and checked by the solver.
// Run: node tools/make-levels.mjs   (deterministic — same output every time)

import { writeFileSync } from 'node:fs';
import { CONFIGS, generateOneMove, generatePuzzle, chainStats } from '../js/generator.js';
import { simulate } from '../js/engine.js';
import { encode } from '../js/codec.js';

// Without arrows every chain runs along one straight line (momentum keeps its direction),
// so long one-move chains only become possible once arrows appear.
const small = { walls: [1, 3], pits: [0, 0], arrows: [0, 0], blocks: [6, 8] };
const smallArrows = { walls: [1, 3], pits: [0, 0], arrows: [1, 2], blocks: [6, 9] };
const smallPits = { walls: [1, 3], pits: [1, 1], arrows: [1, 2], blocks: [6, 9] };

const SPECS = [
  { name: 'First Push', tip: 'Drag a block into others. Momentum passes along. Land the cube on the target.', make: (s) => generateOneMove(s, { cfg: small, minMovers: 2, minMoves: 8 }) },
  { name: 'Two Steps', tip: 'Some puzzles need setup. Match par for three stars.', make: (s) => generatePuzzle(s, { cfg: CONFIGS.basic, minPar: 2, maxPar: 2 }) },
  { name: 'Groundwork', tip: '', make: (s) => generatePuzzle(s, { cfg: CONFIGS.basic, minPar: 3, maxPar: 3 }) },
  { name: 'Turn Signal', tip: 'Arrows turn anything that slides onto them. One move solves this.', make: (s) => generateOneMove(s, { cfg: smallArrows, minMovers: 3, minMoves: 8 }) },
  { name: 'Detour', tip: 'Arrows act on entry. A piece hit while on one moves the way it was hit.', make: (s) => generatePuzzle(s, { cfg: CONFIGS.arrows, minPar: 2, maxPar: 2 }) },
  { name: 'Ricochet', tip: '', make: (s) => generatePuzzle(s, { cfg: CONFIGS.arrows, minPar: 3, maxPar: 3 }) },
  { name: 'Mind the Gap', tip: 'Pits swallow the first piece in, then fill up. Don\'t drop the cube.', make: (s) => generateOneMove(s, { cfg: smallPits, minMovers: 3, minMoves: 8 }) },
  { name: 'Fill the Hole', tip: '', make: (s) => generatePuzzle(s, { cfg: CONFIGS.pits, minPar: 2, maxPar: 2 }) },
  { name: 'Sinkhole', tip: '', make: (s) => generatePuzzle(s, { cfg: CONFIGS.pits, minPar: 3, maxPar: 3 }) },
  { name: 'Crossfire', tip: '', make: (s) => generatePuzzle(s, { cfg: CONFIGS.full, minPar: 3, maxPar: 3 }) },
  { name: 'Long Fuse', tip: '', make: (s) => generatePuzzle(s, { cfg: CONFIGS.full, minPar: 4, maxPar: 4 }) },
  { name: 'Domino Effect', tip: '', make: (s) => generatePuzzle(s, { cfg: CONFIGS.full, minPar: 5, maxPar: 5 }) },
];

function interest(p) {
  let cur = p.state, score = 0;
  for (const m of p.solution) {
    const r = simulate(cur, m.x, m.y, m.dir);
    const st = chainStats(r.events);
    score += st.movers * 3 + st.turns * 2 + st.hits;
    cur = r.state;
  }
  return score / p.solution.length;
}

const levels = SPECS.map((spec, i) => {
  let best = null;
  for (let seed = 1000 * (i + 1); seed < 1000 * (i + 1) + 16; seed++) {
    const p = spec.make(seed);
    if (!p) continue;
    const score = interest(p);
    if (!best || score > best.score) best = { ...p, score };
  }
  if (!best) throw new Error(`No puzzle for level ${i + 1}`);
  console.log(`${String(i + 1).padStart(2)} ${spec.name.padEnd(14)} par ${best.par}  interest ${best.score.toFixed(1)}`);
  return { name: spec.name, tip: spec.tip, code: encode(best.state), par: best.par };
});

const out = `// Generated by tools/make-levels.mjs — edit that script, not this file.
export const LEVELS = ${JSON.stringify(levels, null, 2)};
`;
writeFileSync(new URL('../js/levels.js', import.meta.url), out);
